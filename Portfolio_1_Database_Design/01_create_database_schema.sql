-- 1. FACULTIES
CREATE TABLE faculties (
    faculty_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT
);

-- 2. DEPARTMENTS
CREATE TABLE departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT NOT NULL REFERENCES faculties(faculty_id),
    department_name VARCHAR(150) NOT NULL,
    description TEXT,
    UNIQUE (faculty_id, department_name)
);

-- 3. PROGRAMMES
CREATE TABLE programmes (
    programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(department_id),
    programme_name VARCHAR(200) NOT NULL UNIQUE,
    programme_level VARCHAR(50) NOT NULL DEFAULT 'Master''s'
        CHECK (programme_level = 'Master''s'),
    duration_years NUMERIC(3,1) NOT NULL CHECK (duration_years > 0)
);

-- 4. STUDENTS
CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL REFERENCES programmes(programme_id),
    matric_number VARCHAR(50) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    admission_date DATE NOT NULL,
    student_status VARCHAR(20) NOT NULL
        CHECK (student_status IN ('Active', 'Graduated', 'Suspended', 'Withdrawn'))
);

-- 5. LECTURERS
CREATE TABLE lecturers (
    lecturer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(department_id),
    staff_number VARCHAR(50) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE
);

-- 6. COURSES
CREATE TABLE courses (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(department_id),
    course_code VARCHAR(30) NOT NULL UNIQUE,
    course_title VARCHAR(200) NOT NULL,
    credit_units INTEGER NOT NULL CHECK (credit_units > 0)
);

-- 7. COURSE-PROGRAMME MAPPING
CREATE TABLE course_programmes (
    course_programme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(course_id),
    programme_id BIGINT NOT NULL REFERENCES programmes(programme_id),
    semester VARCHAR(30) NOT NULL,
    UNIQUE (course_id, programme_id, semester)
);

-- 8. ACADEMIC SESSIONS
CREATE TABLE academic_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_name VARCHAR(30) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CHECK (end_date > start_date)
);

-- 9. ENROLMENTS
CREATE TABLE enrolments (
    enrolment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(student_id),
    course_id BIGINT NOT NULL REFERENCES courses(course_id),
    session_id BIGINT NOT NULL REFERENCES academic_sessions(session_id),
    semester VARCHAR(30) NOT NULL,
    enrolment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    enrolment_status VARCHAR(20) NOT NULL
        CHECK (enrolment_status IN ('Registered', 'Completed', 'Dropped')),
    UNIQUE (student_id, course_id, session_id, semester)
);

-- 10. RESULTS
CREATE TABLE results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrolment_id BIGINT NOT NULL UNIQUE REFERENCES enrolments(enrolment_id),
    score NUMERIC(5,2) CHECK (score BETWEEN 0 AND 100),
    grade VARCHAR(5),
    grade_point NUMERIC(3,2) CHECK (grade_point BETWEEN 0 AND 5),
    remarks TEXT
);

